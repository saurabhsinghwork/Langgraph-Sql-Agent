# [Project-Defined Class]: TypedDict tracking state through LangGraph nodes
class AgentState(TypedDict):
    """Execution state preserved across nodes within a single query session."""

    # [Key: str]: The original natural-language query provided by the user
    question: str
    # [Key: str]: Target database ('mca' or 'gst')
    db_type: str
    # [Key: Sequence[BaseMessage]]: Chat history with add_messages reducer
    messages: Annotated[Sequence[BaseMessage], add_messages]
    # [Key: Optional[str]]: The final validated SQL query generated and executed
    sql_query: Optional[str]
    # [Key: List[str]]: Column names returned by the SQL query
    columns: List[str]
    # [Key: List[Dict[str, Any]]]: Result row dictionaries returned from database
    rows: List[Dict[str, Any]]
    # [Key: int]: Number of rows returned
    row_count: int
    # [Key: AgentStatus]: Current execution status enum
    status: AgentStatus
    # [Key: str]: Grounded natural-language explanation generated by Gemini
    explanation: str
    # [Key: Optional[str]]: User-facing sanitized error message if failed
    error_message: Optional[str]
    # [Key: Optional[str]]: Clarification prompt if question was ambiguous
    clarification_prompt: Optional[str]
    # [Key: int]: Current correction retry count for this request
    retry_count: int
    # [Key: int]: Configured maximum retries permitted
    max_retries: int
    # [Key: Optional[str]]: Extracted search keyword token for full-text highlighting
    search_term: Optional[str]
    # [Key: List[str]]: Highlight tokens extracted for universal 'Ctrl + F' search
    highlight_tokens: List[str]


# [Project-Defined Function]: Factory function initializing ChatGoogleGenerativeAI
def create_llm(settings: AppSettings) -> ChatGoogleGenerativeAI:
    """Initialize the configured Gemini Flash-Lite model."""
    # [Variable: str]: Retrieve Gemini API key from settings
    api_key = settings.gemini_api_key
    # [Built-in Python]: Verify key is not empty
    if not api_key:
        raise ValueError(
            "Missing GEMINI_API_KEY. Please provide a valid Gemini API key in your .env file."
        )

    # [Library Class Instance: ChatGoogleGenerativeAI]: Instantiate model
    llm = ChatGoogleGenerativeAI(
        model=settings.gemini_model_id,
        google_api_key=api_key,
        temperature=0.0,
        max_output_tokens=1024,
    )
    return llm


# [Project-Defined Function]: Builds the LangGraph StateGraph workflow for MCA or GST agent
def build_agent_graph(
    db_type: str = "mca",
    settings: Optional[AppSettings] = None,
    tool_service: Optional[DatabaseToolService] = None,
) -> StateGraph:
    """Construct the LangGraph workflow graph for MCA or GST SQL agent orchestration.

    Args:
        db_type: 'mca' or 'gst'.
        settings: Application settings.
        tool_service: Tool service instance for this database.

    Returns:
        Configured StateGraph workflow instance ready for compilation.
    """
    # Normalize database type
    norm_type = db_type.lower().strip()

    # [Project-Defined Function]: Fall back to default singleton settings if omitted
    if settings is None:
        settings = get_settings()
    # [Project-Defined Function]: Fall back to default tool service for db_type if omitted
    if tool_service is None:
        tool_service = get_tool_service(db_type=norm_type)

    # [Project-Defined Function: get_prompt_for_agent]: Select system prompt for MCA or GST
    system_prompt = get_prompt_for_agent(db_type=norm_type)
    # [Project-Defined Function: get_tools_for_agent]: Select tools for MCA or GST
    tools = get_tools_for_agent(db_type=norm_type)

    # [Project-Defined Node Function]: Invoked by LangGraph to call Gemini LLM
    def call_model_node(state: AgentState) -> Dict[str, Any]:
        """Invoke Gemini with system instructions, messages, and bound tools."""
        # [Created Function]: Initialize LLM instance
        llm = create_llm(settings)
        # [Library Method: ChatGoogleGenerativeAI.bind_tools]: Binds tools into model schema
        llm_with_tools = llm.bind_tools(tools)

        # [Built-in Python]: Extract current message list from state dictionary
        current_messages = list(state.get("messages", []))
        # [Built-in Python: isinstance]: Ensure system prompt is prepended as first message
        if not current_messages or not isinstance(current_messages[0], SystemMessage):
            current_messages = [SystemMessage(content=system_prompt)] + current_messages

        # [Library Method: Runnable.invoke]: Call Gemini model with tool schemas
        response = llm_with_tools.invoke(current_messages)
        # Return new message to be appended to state by 'add_messages' reducer
        return {"messages": [response]}

    # [Project-Defined Node Function]: Executes tools requested by model & tracks retries
    def execute_tools_node(state: AgentState) -> Dict[str, Any]:
        """Execute tool calls, evaluate outcomes, and track error corrections."""
        # [Variable: BaseMessage]: Retrieve the most recent message emitted into the graph state
        last_message = state["messages"][-1]
        # [Built-in Python: isinstance]: Verify last message is an AIMessage with requested tool calls
        if not isinstance(last_message, AIMessage) or not last_message.tool_calls:
            return {}

        # [Variable: List[ToolMessage]]: List accumulator for ToolMessage feedback sent back to LLM
        new_tool_messages: List[ToolMessage] = []
        # [Variable: Dict[str, Any]]: State delta dictionary returned to LangGraph to update AgentState
        updates: Dict[str, Any] = {}

        # [Built-in Python: for loop]: Iterate over each tool call requested by Gemini
        for tool_call in last_message.tool_calls:
            # [Variable: str]: The identifier name of the tool called
            tool_name = tool_call["name"]
            # [Variable: dict]: Keyword arguments parsed by the model for the tool
            tool_args = tool_call.get("args", {})
            # [Variable: str]: Unique ID tracking this tool invocation for LLM message pairing
            call_id = tool_call.get("id", "tool_call_id")

            # Check if Gemini requested schema inspection (for MCA or GST)
            if "describe" in tool_name and "schema" in tool_name:
                # [Project-Defined Method: DatabaseToolService.describe_schema]: Generates schema string
                result_str = tool_service.describe_schema()
                new_tool_messages.append(
                    ToolMessage(content=result_str, tool_call_id=call_id)
                )

            # Check if Gemini requested SQL query execution (for MCA or GST)
            elif "execute" in tool_name and "sql" in tool_name:
                # [Variable: str]: Extract SQL string parameter from arguments
                candidate_sql = tool_args.get("query", "")
                # [Project-Defined Method: DatabaseToolService.execute_query]: Validates & runs query
                execution_dict = tool_service.execute_query(candidate_sql)
                # [Library Function: json.dumps]: Serialize output dict to string
                result_str = json.dumps(execution_dict, indent=2)

                # [Project-Defined State Key: 'sql_query']: Record attempted SQL query in agent state
                updates["sql_query"] = candidate_sql

                # [Built-in Python: if]: Check if SQL execution succeeded
                if execution_dict["success"]:
                    # [Variable: List[str]]: Column names from current tool execution
                    new_cols = execution_dict["columns"]
                    # [Variable: List[Dict[str, Any]]]: Data rows from current tool execution
                    new_rows = execution_dict["rows"]
                    # [Variable: int]: Number of rows returned by current query
                    new_count = execution_dict["row_count"]

                    # [Built-in Python: dict.get]: Check if state or current batch already has detailed entity records from a previous tool call
                    existing_rows = updates.get("rows", state.get("rows", []))
                    existing_cols = updates.get("columns", state.get("columns", []))
                    has_detailed_existing = len(existing_rows) > 0 and len(existing_cols) > 1

                    # [Built-in Python: any]: Check if this new result is merely a single scalar count (1 column, 1 row, e.g. COUNT(*))
                    is_scalar_count = (
                        len(new_cols) == 1
                        and any(
                            cnt_kw in new_cols[0].lower()
                            for cnt_kw in ("count", "total", "count(*)", "cnt")
                        )
                        and new_count == 1
                    )

                    # If prior query retrieved detailed multi-column entity records, preserve them over a scalar COUNT(*)
                    if has_detailed_existing and is_scalar_count:
                        # [Library Method: logging.Logger.info]: Log preservation of detailed entity records
                        logger.info(
                            "[%s] Preserving %d detailed entity records over secondary scalar aggregate count.",
                            norm_type.upper(),
                            len(existing_rows),
                        )
                        # Keep existing detailed records for tabular presentation
                        updates["columns"] = existing_cols
                        updates["rows"] = existing_rows
                        updates["row_count"] = len(existing_rows)
                        updates["sql_query"] = updates.get("sql_query", state.get("sql_query", candidate_sql))
                    else:
                        # [Project-Defined State Keys]: Store column names, result rows, and row count
                        updates["columns"] = new_cols
                        updates["rows"] = new_rows
                        updates["row_count"] = new_count
                        updates["sql_query"] = candidate_sql

                    # [Project-Defined Enum: AgentStatus.SUCCESS]
                    updates["status"] = AgentStatus.SUCCESS
                    updates["error_message"] = None
                else:
                    # [Variable: str]: Extract error classification and description from execution result
                    status = execution_dict.get("status", "execution_failed")
                    error = execution_dict.get("error", "Unknown execution error")
                    updates["error_message"] = error

                    # Check if query was blocked by AST security validator
                    if status == "validation_rejected":
                        updates["status"] = AgentStatus.VALIDATION_REJECTED
                    else:
                        is_retryable = execution_dict.get("is_retryable", False)
                        current_retry = state.get("retry_count", 0)
                        max_retries = state.get("max_retries", settings.sql_correction_max_retries)

                        # Check if within retry budget for automatic error correction
                        if is_retryable and current_retry < max_retries:
                            updates["retry_count"] = current_retry + 1
                            updates["status"] = AgentStatus.EXECUTION_FAILED
                            remaining = max_retries - (current_retry + 1)
                            result_str += (
                                f"\n\n[CORRECTION NOTICE]: The query failed with a correctable error. "
                                f"You have {remaining} retry attempts remaining. "
                                f"Please review the live {norm_type.upper()} schema, correct the SQL query, and call the execution tool again."
                            )
                        else:
                            updates["status"] = AgentStatus.RETRY_EXHAUSTED

                new_tool_messages.append(
                    ToolMessage(content=result_str, tool_call_id=call_id)
                )

            # Check if Gemini requested global full-text search (for MCA or GST)
            elif "full_text_search" in tool_name or "search" in tool_name:
                # [Variable: str]: Extract search query keyword
                search_query = tool_args.get("query") or tool_args.get("keyword") or tool_args.get("search_term") or ""
                # [Variable: Any]: Extract optional LLM-expanded synonyms or variations
                raw_expanded = tool_args.get("expanded_terms")
                expanded_terms: Optional[List[str]] = None
                if isinstance(raw_expanded, list):
                    expanded_terms = [str(t).strip() for t in raw_expanded if str(t).strip()]
                elif isinstance(raw_expanded, str) and raw_expanded.strip():
                    expanded_terms = [t.strip() for t in raw_expanded.split(",") if t.strip()]

                # [Project-Defined Method: DatabaseToolService.full_text_search]: Execute universal multi-column search
                execution_dict = tool_service.full_text_search(search_query, expanded_terms=expanded_terms)
                # [Library Function: json.dumps]: Serialize output dict to string
                result_str = json.dumps(execution_dict, indent=2)

                # [Project-Defined State Key: 'sql_query']: Record search SQL query in agent state
                updates["sql_query"] = execution_dict.get("sql_query", f"-- Full-Text Search: '{search_query}'")

                if execution_dict["success"]:
                    new_cols = execution_dict["columns"]
                    new_rows = execution_dict["rows"]
                    new_count = execution_dict["row_count"]

                    updates["columns"] = new_cols
                    updates["rows"] = new_rows
                    updates["row_count"] = new_count
                    updates["search_term"] = search_query
                    updates["highlight_tokens"] = execution_dict.get("highlight_tokens", [])
                    updates["status"] = AgentStatus.SUCCESS
                    updates["error_message"] = None
                else:
                    updates["status"] = AgentStatus.EXECUTION_FAILED
                    updates["error_message"] = execution_dict.get("error", "Full-text search execution failed")
                    updates["highlight_tokens"] = execution_dict.get("highlight_tokens", [])

                new_tool_messages.append(
                    ToolMessage(content=result_str, tool_call_id=call_id)
                )

        updates["messages"] = new_tool_messages
        return updates

    # [Project-Defined Routing Function]: Conditional edge decider evaluated after LLM response
    def route_after_model(state: AgentState) -> str:
        """Route to tool execution or finalize answer."""
        last_message = state["messages"][-1]
        if isinstance(last_message, AIMessage) and last_message.tool_calls:
            return "tools"
        return "finalize"

    # [Project-Defined Node Function]: Terminal node constructing user explanation and final status
    def finalize_node(state: AgentState) -> Dict[str, Any]:
        """Construct the final natural-language explanation and determine final status."""
        last_message = state["messages"][-1]
        raw_content = last_message.content if isinstance(last_message, AIMessage) else ""

        # Normalize content payload
        if isinstance(raw_content, list):
            texts = []
            for part in raw_content:
                if isinstance(part, str):
                    texts.append(part)
                elif isinstance(part, dict) and "text" in part:
                    texts.append(part["text"])
            content = "\n".join(texts).strip()
        else:
            content = str(raw_content).strip()

        sql_query = state.get("sql_query")

        # If no query was executed, test if response is asking user for clarification
        if sql_query is None:
            clarification_indicators = (
                "clarify",
                "clarification",
                "which metric",
                "could you specify",
                "please specify",
                "do you mean",
                "ambiguous",
            )
            if any(ind in content.lower() for ind in clarification_indicators):
                return {
                    "explanation": content,
                    "clarification_prompt": content,
                    "status": AgentStatus.CLARIFICATION_REQUIRED,
                }

        return {"explanation": content}

    # [Library Class Instance: StateGraph]: Assemble workflow
    workflow = StateGraph(AgentState)
    workflow.add_node("model", call_model_node)
    workflow.add_node("tools", execute_tools_node)
    workflow.add_node("finalize", finalize_node)

    workflow.set_entry_point("model")

    workflow.add_conditional_edges(
        "model",
        route_after_model,
        {
            "tools": "tools",
            "finalize": "finalize",
        },
    )
    workflow.add_edge("tools", "model")
    workflow.add_edge("finalize", END)

    return workflow


# [Project-Defined Function]: High-level entry point executing SQL agent for either MCA or GST database
def run_agent(
    question: str,
    db_type: str = "mca",
    settings: Optional[AppSettings] = None,
    tool_service: Optional[DatabaseToolService] = None,
) -> AgentResult:
    """Execute the LangGraph SQL Agent for MCA or GST database on a natural-language query.

    Args:
        question: User's natural-language query.
        db_type: 'mca' or 'gst'.
        settings: Application settings.
        tool_service: Tool service instance.

    Returns:
        Structured AgentResult contract.
    """
    norm_type = db_type.lower().strip()
    if settings is None:
        settings = get_settings()
    if tool_service is None:
        tool_service = get_tool_service(db_type=norm_type)

    cleaned_question = question.strip()
    if not cleaned_question:
        return AgentResult(
            status=AgentStatus.CONFIGURATION_ERROR,
            question=question,
            explanation=f"Please enter a non-empty question to query the {norm_type.upper()} database.",
        )

    # Check configuration readiness
    issues = settings.validate_runtime_readiness()
    if issues:
        logger.warning("[%s] Configuration issues detected: %s", norm_type.upper(), issues)
        return AgentResult(
            status=AgentStatus.CONFIGURATION_ERROR,
            question=cleaned_question,
            explanation="Configuration Error:\n" + "\n".join(f"- {i}" for i in issues),
            error_message="Missing required runtime configuration (e.g. GEMINI_API_KEY).",
        )

    # Check database readiness
    db_connected, db_msg = tool_service.inspector.verify_schema_integrity()
    if not db_connected:
        logger.warning("[%s] Database schema check failed: %s", norm_type.upper(), db_msg)

    # Initialize agent state
    initial_state: AgentState = {
        "question": cleaned_question,
        "db_type": norm_type,
        "messages": [HumanMessage(content=cleaned_question)],
        "sql_query": None,
        "columns": [],
        "rows": [],
        "row_count": 0,
        "status": AgentStatus.SUCCESS,
        "explanation": "",
        "error_message": None,
        "clarification_prompt": None,
        "retry_count": 0,
        "max_retries": settings.sql_correction_max_retries,
        "search_term": None,
        "highlight_tokens": [],
    }

    try:
        # Build and invoke workflow graph
        graph = build_agent_graph(db_type=norm_type, settings=settings, tool_service=tool_service)
        app = graph.compile()
        final_state = app.invoke(initial_state)

        status = final_state.get("status", AgentStatus.SUCCESS)
        raw_exp = final_state.get("explanation", "")
        if isinstance(raw_exp, list):
            explanation = " ".join(p.get("text", str(p)) if isinstance(p, dict) else str(p) for p in raw_exp).strip()
        else:
            explanation = str(raw_exp).strip()

        raw_clar = final_state.get("clarification_prompt")
        clarification_prompt = None
        if raw_clar is not None:
            if isinstance(raw_clar, list):
                clarification_prompt = " ".join(p.get("text", str(p)) if isinstance(p, dict) else str(p) for p in raw_clar).strip()
            else:
                clarification_prompt = str(raw_clar).strip()

        return AgentResult(
            status=status,
            question=cleaned_question,
            explanation=explanation,
            sql_query=final_state.get("sql_query"),
            columns=final_state.get("columns", []),
            rows=final_state.get("rows", []),
            row_count=final_state.get("row_count", 0),
            error_message=final_state.get("error_message"),
            clarification_prompt=clarification_prompt,
            retry_count=final_state.get("retry_count", 0),
            search_term=final_state.get("search_term"),
            highlight_tokens=final_state.get("highlight_tokens", []),
        )

    except Exception as exc:
        logger.exception("[%s] Agent execution failed unexpectedly: %s", norm_type.upper(), exc)
        return AgentResult(
            status=AgentStatus.EXECUTION_FAILED,
            question=cleaned_question,
            explanation=f"The {norm_type.upper()} agent encountered an unexpected error while processing your request.",
            error_message=f"Agent runtime error: {type(exc).__name__}",
        )


# [Project-Defined Function]: Shortcut runner executing the MCA Corporate Agent
def run_mca_agent(
    question: str,
    settings: Optional[AppSettings] = None,
    tool_service: Optional[DatabaseToolService] = None,
) -> AgentResult:
    """Execute the MCA Corporate Data Agent."""
    return run_agent(question=question, db_type="mca", settings=settings, tool_service=tool_service)


# [Project-Defined Function]: Shortcut runner executing the GST Taxpayer Agent
def run_gst_agent(
    question: str,
    settings: Optional[AppSettings] = None,
    tool_service: Optional[DatabaseToolService] = None,
) -> AgentResult:
    """Execute the GST Taxpayer Data Agent."""
    return run_agent(question=question, db_type="gst", settings=settings, tool_service=tool_service)
